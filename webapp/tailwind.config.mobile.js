// Tailwind 3 config for the phone's build.
//
// The desktop build uses Tailwind 4, whose CSS is built on @layer, color-mix()
// and oklch(). Safari learned @layer in 15.4 and color-mix in 16.2, so on iOS 9
// - where 85% of the desktop stylesheet was silently dropped - the page
// rendered unstyled. Tailwind 3 emits flat CSS that goes back to Safari 9.
//
// The colours are literal values, not CSS custom properties. Safari on iOS has
// no support for custom properties at all before 9.3 (partial) and 10 (full),
// and the phone runs 9.2 - so a var() in a colour is not just ignored, the
// whole declaration is dropped and the element ends up with no colour at all.
// The two themes are therefore two separate stylesheets, built one at a time,
// and the page enables one of them.

